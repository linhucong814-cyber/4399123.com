function load(key, fallback) {
  try {
    return JSON.parse(localStorage.getItem(key)) ?? fallback;
  } catch {
    return fallback;
  }
}

function save() {
  try {
    localStorage.setItem("promptHistory", JSON.stringify(state.history.slice(0, 60)));
    localStorage.setItem("promptFavorites", JSON.stringify(state.favorites));
    localStorage.setItem(
      "promptConfig",
      JSON.stringify({
        category: state.category,
        locked: state.locked,
        values: state.values,
        shuffleOrder: state.shuffleOrder,
      }),
    );
  } catch {
    showToast("浏览器限制了本地保存");
  }
}

function createId() {
  return globalThis.crypto?.randomUUID
    ? globalThis.crypto.randomUUID()
    : `id-${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

function pick(items) {
  return items[Math.floor(Math.random() * items.length)];
}

function shuffle(items) {
  const next = [...items];
  for (let index = next.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(Math.random() * (index + 1));
    [next[index], next[swapIndex]] = [next[swapIndex], next[index]];
  }
  return next;
}

function makePrompt(variation = false) {
  Object.entries(banks).forEach(([key, bank]) => {
    if (!state.locked[key] || !state.values[key] || variation) {
      if (!state.locked[key]) state.values[key] = pick(bank.values);
    }
  });

  const title = titleFrom([state.values.subject, state.values.scene].filter(Boolean).join(""));
  const activeKeys = promptOrder.filter(
    (key) => state.values[key] && (requiredPromptKeys.includes(key) || state.locked[key] || Math.random() > 0.24),
  );
  const orderedParts = activeKeys.map((key) => ({
    key,
    locked: Boolean(state.locked[key]),
    value: state.values[key],
  }));
  const descriptiveParts = state.shuffleOrder ? shuffleUnlockedParts(orderedParts) : orderedParts.map((part) => part.value);
  const prompt = [...descriptiveParts, state.values.ratio].filter(Boolean).join(", ");

  const item = {
    id: createId(),
    title,
    category: state.category,
    prompt,
    negative: "低质量、模糊、畸形结构、水印、乱码文字、多余手指、杂乱排版、过曝、欠曝",
    tone: pick(tones),
    createdAt: new Date().toISOString(),
  };

  state.current = item;
  state.history = [item, ...state.history.filter((entry) => entry.prompt !== prompt)].slice(0, 60);
  save();
  renderAll();
}

function shuffleUnlockedParts(parts) {
  const unlockedValues = shuffle(parts.filter((part) => !part.locked).map((part) => part.value));
  let cursor = 0;
  return parts.map((part) => (part.locked ? part.value : unlockedValues[cursor++]));
}

function titleFrom(subject) {
  const clean = subject.replace(/^a |^an /i, "").replace(/[，,].*$/, "");
  if (/[\u4e00-\u9fa5]/.test(clean)) return clean.slice(0, 16);
  return clean
    .split(" ")
    .slice(0, 4)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

function renderCategories() {
  els.categoryChips.innerHTML = categories
    .map(
      (category) =>
        `<button class="chip ${category === state.category ? "active" : ""}" type="button" data-category="${category}" aria-pressed="${category === state.category}">${category}</button>`,
    )
    .join("");
}

function renderControls() {
  els.shuffleOrderToggle.checked = state.shuffleOrder;
  els.controls.innerHTML = Object.entries(banks)
    .map(([key, bank]) => {
      const value = state.values[key] ?? bank.values[0];
      const hasValueInBank = bank.values.includes(value);
      const options = [
        ...(!hasValueInBank ? [`<option value="${escapeHtml(value)}" selected>自定义：${escapeHtml(value)}</option>`] : []),
        ...bank.values.map((item) => `<option value="${escapeHtml(item)}"${item === value ? " selected" : ""}>${item}</option>`),
      ];
      return `
        <div class="control">
          <label for="${key}Select">
            ${bank.label}
            <button class="lock ${state.locked[key] ? "active" : ""}" type="button" data-lock="${key}" aria-pressed="${Boolean(state.locked[key])}">${state.locked[key] ? "已锁" : "锁定"}</button>
          </label>
          <select id="${key}Select" data-select="${key}">${options.join("")}</select>
          <input class="custom-param" type="text" data-custom="${key}" value="${escapeHtml(value)}" placeholder="直接编辑${bank.label}" />
        </div>
      `;
    })
    .join("");
}

function renderOutput() {
  const current = state.current;
  els.activeCategory.textContent = current?.category ?? state.category;
  els.promptTitle.textContent = current?.title ?? "准备生成";
  els.promptOutput.value = current?.prompt ?? "点击生成按钮，随机收纳一条 image 提示词。";
  els.negativeOutput.textContent = current?.negative ?? "低质量、模糊、畸形结构、水印、乱码文字、杂乱构图";
  els.previewCaption.textContent = current?.title ?? "等待生成";
  els.favoriteBtn.textContent = current && isFavorite(current.prompt) ? "★" : "☆";

  const tone = current?.tone ?? tones[0];
  els.previewCard.style.setProperty("--tone-a", tone[0]);
  els.previewCard.style.setProperty("--tone-b", tone[1]);
  els.previewCard.style.background = `radial-gradient(circle at 72% 24%, rgba(255,255,255,.86), transparent 12%), linear-gradient(135deg, ${tone[0]}, ${tone[1]})`;
}

function renderList() {
  const query = els.searchInput.value.trim().toLowerCase();
  const source =
    state.view === "history" ? state.history : state.view === "favorites" ? state.favorites : seedPrompts.map(seedToItem);
  const filtered = source.filter((item) => `${item.title} ${item.category} ${item.prompt}`.toLowerCase().includes(query));

  if (!filtered.length) {
    els.promptList.innerHTML = `<div class="empty-state">这里还没有匹配的提示词。生成几条，灵感就会慢慢堆起来。</div>`;
    return;
  }

  els.promptList.innerHTML = filtered
    .map((item, index) => {
      const tone = item.tone ?? tones[index % tones.length];
      return `
        <article class="prompt-card" style="--tone-a:${tone[0]};--tone-b:${tone[1]}">
          <div class="thumb" aria-hidden="true"></div>
          <div>
            <h3>${escapeHtml(item.title)}</h3>
            <p>${escapeHtml(item.prompt)}</p>
          </div>
          <div class="card-actions">
            <button type="button" data-use="${item.id}">使用</button>
            <button type="button" data-copy="${item.id}">复制</button>
            <button type="button" data-fav="${item.id}">${isFavorite(item.prompt) ? "取消收藏" : "收藏"}</button>
          </div>
        </article>
      `;
    })
    .join("");
}

function seedToItem(seed, index) {
  return {
    id: `seed-${index}-${seed.title}`,
    ...seed,
    negative: "低质量、模糊、水印、构图混乱、乱码文字",
    tone: tones[index % tones.length],
  };
}

function renderStats() {
  els.historyCount.textContent = state.history.length;
  els.favoriteCount.textContent = state.favorites.length;
}

function renderAll() {
  renderCategories();
  renderControls();
  renderOutput();
  renderStats();
  renderList();
}

function isFavorite(prompt) {
  return state.favorites.some((item) => item.prompt === prompt);
}

function toggleFavorite(item = state.current) {
  if (!item) return showToast("先生成一条提示词");
  if (isFavorite(item.prompt)) {
    state.favorites = state.favorites.filter((entry) => entry.prompt !== item.prompt);
    showToast("已取消收藏");
  } else {
    state.favorites = [{ ...item, id: createId() }, ...state.favorites];
    showToast("已收藏");
  }
  save();
  renderAll();
}

async function copyPrompt(prompt = state.current?.prompt) {
  if (!prompt) return showToast("先生成一条提示词");
  try {
    await navigator.clipboard.writeText(prompt);
    showToast("提示词已复制");
  } catch {
    els.promptOutput.value = prompt;
    els.promptOutput.focus();
    els.promptOutput.select();
    showToast("已选中提示词，请手动复制");
  }
}

function findItem(id) {
  const all = [...state.history, ...state.favorites, ...seedPrompts.map(seedToItem)];
  return all.find((item) => item.id === id);
}

function showToast(message) {
  els.toast.textContent = message;
  els.toast.classList.add("show");
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(() => els.toast.classList.remove("show"), 1800);
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

document.addEventListener("click", (event) => {
  const target = event.target.closest("button");
  if (!target) return;

  if (target.dataset.category) {
    state.category = target.dataset.category;
    save();
    renderCategories();
  }

  if (target.dataset.lock) {
    const key = target.dataset.lock;
    state.locked[key] = !state.locked[key];
    save();
    renderControls();
  }

  if (target.dataset.use) {
    const item = findItem(target.dataset.use);
    if (item) {
      state.current = { ...item, id: createId() };
      state.category = item.category;
      renderAll();
      showToast("已载入提示词");
    }
  }

  if (target.dataset.copy) {
    const item = findItem(target.dataset.copy);
    if (item) copyPrompt(item.prompt);
  }

  if (target.dataset.fav) {
    const item = findItem(target.dataset.fav);
    toggleFavorite(item);
  }
});

document.addEventListener("change", (event) => {
  const key = event.target.dataset.select;
  if (event.target === els.shuffleOrderToggle) {
    state.shuffleOrder = event.target.checked;
    save();
    showToast(state.shuffleOrder ? "已开启随机排序" : "已关闭随机排序");
    return;
  }
  if (!key) return;
  state.values[key] = event.target.value;
  state.locked[key] = true;
  save();
  renderControls();
});

document.addEventListener("input", (event) => {
  const key = event.target.dataset.custom;
  if (!key) return;
  const value = event.target.value.trim();
  if (!value) return;
  state.values[key] = value;
  state.locked[key] = true;
  save();
  const lockButton = event.target.closest(".control")?.querySelector(".lock");
  if (lockButton) {
    lockButton.classList.add("active");
    lockButton.textContent = "已锁";
  }
});

